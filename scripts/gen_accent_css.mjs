// Generates the per-accent CSS blocks for src/index.css from Tailwind's own palette
// (node_modules/tailwindcss/theme.css) so every shade is accurate, not hand-guessed.
// Run: node scripts/gen_accent_css.mjs  -> prints CSS to stdout (redirect into a file).
import { readFileSync } from 'node:fs';

const TW = readFileSync(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// palette name per accent id (green = default, needs no overrides)
const ACCENTS = [
  { id: 'pink', pal: 'pink' },
  { id: 'red', pal: 'red' },
  { id: 'blue', pal: 'sky' },
  { id: 'purple', pal: 'violet' },
  { id: 'orange', pal: 'orange' },
];

function getPalette(pal) {
  const out = {};
  for (const s of SHADES) {
    const m = TW.match(new RegExp(`--color-${pal}-${s}:\\s*([^;]+);`));
    if (!m) throw new Error(`missing --color-${pal}-${s}`);
    out[s] = m[1].trim();
  }
  return out;
}

// oklch -> sRGB (for --tint-leaf "r, g, b" triples used inside rgba())
function oklchToRgb(str) {
  const m = str.match(/oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)/);
  if (!m) throw new Error(`not oklch: ${str}`);
  const L = parseFloat(m[1]) / 100, C = parseFloat(m[2]), H = parseFloat(m[3]);
  const h = (H * Math.PI) / 180;
  const a = Math.cos(h) * C, b = Math.sin(h) * C;
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.2914855480 * b;
  const l = l_ ** 3, mm = m_ ** 3, s = s_ ** 3;
  const r = +4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s;
  const g = -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s;
  const bl = -0.0041960863 * l - 0.7034186147 * mm + 1.7076147010 * s;
  const gam = (v) => {
    const x = Math.min(1, Math.max(0, v));
    return Math.round(255 * (x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055));
  };
  return `${gam(r)}, ${gam(g)}, ${gam(bl)}`;
}

const lines = [];
lines.push('');
lines.push('/* ============================================================');
lines.push('   Mavzu rangi (accent themes) — Settings → "Mavzu rangi".');
lines.push('   html[data-accent=…] rewrites the emerald and teal utility palette');
lines.push('   (ALL emerald-* and teal-* utility classes recolour at once) plus the');
lines.push('   semantic leaf vars. "green" (default) sets no attribute, so the');
lines.push('   original palette above stays pixel-identical. Shades come from');
lines.push('   Tailwind\'s own theme so contrast (white-on-500 etc.) is preserved.');
lines.push('   Generated by scripts/gen_accent_css.mjs — do not hand-edit shades.');
lines.push('   ============================================================ */');

for (const { id, pal } of ACCENTS) {
  const p = getPalette(pal);
  lines.push('');
  lines.push(`html[data-accent='${id}'] {`);
  for (const s of SHADES) lines.push(`  --color-emerald-${s}: ${p[s]};`);
  for (const s of SHADES) lines.push(`  --color-teal-${s}: ${p[s]};`);
  lines.push(`  --tint-leaf: ${oklchToRgb(p[500])};`);
  lines.push('  --c-app: color-mix(in srgb, var(--color-emerald-50) 55%, white);');
  lines.push('  --c-surface2: color-mix(in srgb, var(--color-emerald-100) 45%, white);');
  lines.push('  --c-line: color-mix(in srgb, var(--color-emerald-200) 35%, white);');
  lines.push('  --c-leaf: var(--color-emerald-400);');
  lines.push('  --c-accent: var(--color-emerald-500);');
  lines.push('  --c-leaf-hi: var(--color-emerald-300);');
  lines.push('  --c-leaf-lo: var(--color-emerald-600);');
  lines.push('  --c-leaf-deep: var(--color-emerald-600);');
  lines.push('  --c-leaf-soft: var(--color-emerald-300);');
  lines.push('  --c-leaf-arm: var(--color-emerald-300);');
  lines.push('  --c-leaf-pale: var(--color-emerald-200);');
  lines.push('  --c-leaf-sprout: var(--color-emerald-400);');
  lines.push('  --c-nav-hi: var(--color-emerald-400);');
  lines.push('  --c-dot-top: var(--color-emerald-600);');
  lines.push('  --c-hill-hi: var(--color-emerald-300);');
  lines.push('  --c-hill-lo: var(--color-emerald-400);');
  lines.push('  --c-planet-hi: var(--color-emerald-300);');
  lines.push('  --c-planet-mid: var(--color-emerald-500);');
  lines.push('  --c-planet-deep: var(--color-emerald-800);');
  lines.push(`  --c-aurora: ${p[600]};`);
  lines.push('}');
  lines.push(`html.dark[data-accent='${id}'] {`);
  lines.push('  --c-leaf: var(--color-emerald-400);');
  lines.push('  --c-accent: var(--color-emerald-400);');
  lines.push('}');
}

// swatch info for src/lib/theme.ts ACCENTS (oklch strings — browsers already render oklch via Tailwind)
console.error('// theme.ts swatches:');
for (const { id, pal } of ACCENTS) {
  const p = getPalette(pal);
  console.error(`  { id: '${id}', name: '…', swatch: '${p[400]}' },`);
}
process.stdout.write(lines.join('\n') + '\n');
